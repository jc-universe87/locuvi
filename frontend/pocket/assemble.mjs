// Packs the phone app: the pocket web build (dist-pocket/) plus everything Locuvi's backend
// needs to run in Pyodide, all under dist-pocket/pocket/, and a service worker that keeps the
// whole app on the phone for offline use (iPhone and iPad Home Screen app).
//
//   VITE_POCKET=1 vite build && node pocket/assemble.mjs
//
// Inputs (environment):
//   PYODIDE_DIR    an unpacked Pyodide release (pyodide-<version>.tar.bz2 from GitHub)
//   POCKET_WHEELS  folder with Locuvi's wheel and the pure-Python wheels Pyodide lacks
import { copyFileSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, relative } from "node:path";

const OUT = new URL("../dist-pocket/", import.meta.url).pathname;
const PYODIDE = process.env.PYODIDE_DIR;
const WHEELS = process.env.POCKET_WHEELS;
if (!PYODIDE || !WHEELS) throw new Error("Set PYODIDE_DIR and POCKET_WHEELS");

// What Locuvi imports from Pyodide's own builds (C extensions compiled to WebAssembly).
const PACKAGES = ["micropip", "pydantic", "sqlalchemy", "cryptography", "lxml", "pillow", "tzdata",
  "httpx", "starlette", "fastapi", "markupsafe", "pyyaml", "jiter", "anyio", "typing-inspection"];
const RUNTIME = ["pyodide.mjs", "pyodide.asm.mjs", "pyodide.asm.wasm", "python_stdlib.zip", "pyodide-lock.json"];

const norm = (n) => n.toLowerCase().replace(/[-_.]+/g, "-");
const lock = JSON.parse(readFileSync(join(PYODIDE, "pyodide-lock.json"), "utf8"));
const byName = Object.fromEntries(Object.entries(lock.packages).map(([k, v]) => [norm(k), v]));
const need = new Set();
const todo = [...PACKAGES];
while (todo.length) {
  const n = norm(todo.pop());
  if (need.has(n)) continue;
  if (!byName[n]) throw new Error(`Pyodide has no package ${n}`);
  need.add(n);
  todo.push(...(byName[n].depends ?? []));
}

mkdirSync(join(OUT, "pocket", "pyodide"), { recursive: true });
mkdirSync(join(OUT, "pocket", "wheels"), { recursive: true });
for (const f of RUNTIME) copyFileSync(join(PYODIDE, f), join(OUT, "pocket", "pyodide", f));
for (const n of need) {
  const f = byName[n].file_name;
  copyFileSync(join(PYODIDE, f), join(OUT, "pocket", "pyodide", f));
}
const wheels = readdirSync(WHEELS).filter((f) => f.endsWith(".whl")).sort();
if (!wheels.some((w) => w.startsWith("locuvi-"))) throw new Error("Locuvi's own wheel is missing");
for (const w of wheels) copyFileSync(join(WHEELS, w), join(OUT, "pocket", "wheels", w));
writeFileSync(join(OUT, "pocket", "manifest.json"),
  JSON.stringify({ pyodide: lock.info?.version ?? "", packages: [...need].sort(), wheels }, null, 1));

// Service worker: every file of the app, cached on first open, so it opens without internet.
const files = [];
const walk = (d) => {
  for (const f of readdirSync(d)) {
    const p = join(d, f);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(relative(OUT, p).split("\\").join("/"));
  }
};
walk(OUT);
const list = files.filter((f) => f !== "sw.js").sort();
const version = createHash("sha256").update(list.join("\n")).update(readFileSync(join(OUT, "index.html"))).digest("hex").slice(0, 12);
writeFileSync(join(OUT, "sw.js"), `// Generated by pocket/assemble.mjs: keeps Locuvi on this device for offline use.
const CACHE = "locuvi-${version}";
const FILES = ${JSON.stringify(["./", ...list])};
self.addEventListener("install", (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())));
self.addEventListener("activate", (e) => e.waitUntil(caches.keys().then((keys) =>
  Promise.all(keys.filter((k) => k.startsWith("locuvi-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim())));
self.addEventListener("fetch", (e) => {
  const url = new URL(e.request.url);
  if (e.request.method !== "GET" || url.origin !== location.origin) return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then((hit) => hit || fetch(e.request)));
});
`);
const size = files.reduce((t, f) => t + statSync(join(OUT, f)).size, 0);
console.log(`phone app: ${files.length} files, ${(size / 1e6).toFixed(1)} MB, ${need.size} Pyodide packages, ${wheels.length} wheels`);
